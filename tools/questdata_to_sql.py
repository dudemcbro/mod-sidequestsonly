#!/usr/bin/env python3
"""
questdata_to_sql.py - Turn the classifier's output into the module's world SQL.

Reads the per-chain map in category_assignments.json (from classify_quests.py)
or QC_QuestCategory from an old v1 QuestData.lua, and writes
data/sql/world/mod_sidequestsonly_quest.sql. It stops when the classifier left
chains without an LLM answer, unless --allow-incomplete (those quests are left
out and show as [?]).

    python3 tools/questdata_to_sql.py QuestData.lua
    python3 tools/questdata_to_sql.py category_assignments.json -o out.sql

The SQL uses INSERT IGNORE, so classifications a GM changed in game with
.sqo set are kept. Pass --replace to overwrite them with the file's values.
"""

import argparse
import json
import os
import re
import sys

CATEGORIES = (
    "intro", "story", "lore", "attune", "class", "profession", "daily", "pvp",
    "holiday", "event", "dungeon_story", "dungeon_lore", "dungeon_side",
    "raid_story", "raid_lore", "raid_side", "side",
)
ROWS_PER_INSERT = 500
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "data", "sql", "world",
                           "mod_sidequestsonly_quest.sql")


def from_lua(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    pairs = re.findall(r'^_c\[(\d+)\]\s*=\s*"(\w+)"', text, re.M)
    return {int(q): c for q, c in pairs}


def from_json(path, allow_incomplete=False):
    with open(path, encoding="utf-8") as f:
        chains = json.load(f)
    pending = [c for c in chains.values() if c.get("needs_llm") and not c.get("llm_done")]
    if pending and not allow_incomplete:
        sys.exit(f"{len(pending)} chains in {path} still need the LLM: run "
                 "classify_quests.py --resume, or pass --allow-incomplete")
    result = {}
    for chain in chains.values():
        # Older files have one category per chain and no quest_categories.
        per_quest = chain.get("quest_categories")
        for quest in chain.get("quest_ids", []):
            category = per_quest.get(str(quest)) if per_quest is not None else chain["category"]
            if category:
                result[int(quest)] = category
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", help="QuestData.lua or category_assignments.json")
    parser.add_argument("-o", "--output", default=DEFAULT_OUT)
    parser.add_argument("--replace", action="store_true",
                        help="overwrite existing rows instead of keeping them")
    parser.add_argument("--allow-incomplete", action="store_true",
                        help="write the SQL even if some chains have no LLM answer yet")
    args = parser.parse_args()

    if args.source.endswith(".json"):
        quests = from_json(args.source, args.allow_incomplete)
    else:
        quests = from_lua(args.source)
    if not quests:
        sys.exit(f"No classifications found in {args.source}")
    unknown = sorted({c for c in quests.values() if c not in CATEGORIES})
    if unknown:
        sys.exit(f"Unknown categories in {args.source}: {', '.join(unknown)}")

    verb = "REPLACE" if args.replace else "INSERT IGNORE"
    ids = sorted(quests)
    lines = [
        "-- mod-sidequestsonly: quest categories",
        "-- Apply to: acore_world",
        f"-- Generated by tools/questdata_to_sql.py from {os.path.basename(args.source)}"
        f" ({len(ids)} quests).",
        "",
        "CREATE TABLE IF NOT EXISTS `mod_sidequestsonly_quest` (",
        "  `QuestId` INT UNSIGNED NOT NULL,",
        "  `Category` VARCHAR(16) NOT NULL,",
        "  PRIMARY KEY (`QuestId`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;",
    ]
    for start in range(0, len(ids), ROWS_PER_INSERT):
        chunk = ids[start:start + ROWS_PER_INSERT]
        lines.append("")
        lines.append(f"{verb} INTO `mod_sidequestsonly_quest` (`QuestId`, `Category`) VALUES")
        rows = [f"({q},'{quests[q]}')" for q in chunk]
        lines.append(",\n".join(rows) + ";")

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(ids)} quests to {args.output}")


if __name__ == "__main__":
    main()
